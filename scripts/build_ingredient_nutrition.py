def normalize(name):
    """归一化：显式别名 → 正则清洗 → 类别回退。返回基础名。"""
    name = name.strip()
    if name in ALIASES:
        return ALIASES[name]
    if name in BASE:
        return name
    # 正则清洗：去括号、去"或"之后、去数量词、去部位后缀
    cleaned = name
    cleaned = re.sub(r'（[^）]*）|\([^)]*\)', '', cleaned)  # 去括号
    cleaned = cleaned.split('或')[0].split('、')[0]  # 去选择词
    cleaned = re.sub(r'(\d+(\.\d+)?(只|个|克|g|斤|两|片|块|根|条|段|头))|半只|整只|1只|半$', '', cleaned)
    cleaned = re.sub(r'(块|片|皮|丝|末|丁|粒|圈|须|半)$', '', cleaned)
    cleaned = cleaned.strip()
    if cleaned in BASE:
        return cleaned
    if cleaned in ALIASES:
        return ALIASES[cleaned]
    return name  # 仍无法归一化，保留原名供回退


