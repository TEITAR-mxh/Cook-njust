def main():
    with open(RECIPE_JSON, encoding='utf-8') as f:
        data = json.load(f)
    counter = Counter()
    for r in data:
        for s in r.get('stuff', []):
            counter[s] += 1

    out = {}
    missing = []  # 走了 fallback 的原始名（未在 BASE 精确命中）
    for raw in counter:
        base = normalize(raw)
        if base in BASE:
            out[raw] = BASE[base]
        else:
            out[raw] = fallback(raw)
            missing.append(raw)

    # 输出：key = 原始食材名
    with open(OUT_JSON, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=0)

    precise = sum(1 for v in out.values() if v['source'] == '成分表')
    estimate = sum(1 for v in out.values() if v['source'] == '估算')
    print(f'总食材名: {len(out)}')
    print(f'精确(成分表): {precise}  估算: {estimate}')
    print(f'走类别回退(未精确命中): {len(missing)}')
    if missing:
        print('--- 未精确命中的食材名 ---')
        for m in sorted(missing):
            print(f'  {m}')


if __name__ == '__main__':
    main()
